using FluentAssertions;
using Pricing.Application.Queries.Markup;
using Pricing.Entities;
using Tests.PricingTests.DataBuilders.Markup;

namespace Tests.PricingTests.HandlerTests.Markup;

public sealed class GetMarkupGroupsByIdsTests(ReadScenarioFixture<GetMarkupGroupsByIdsTests.MarkupGroupsByIdsScenario> fixture)
	: ReadScenarioTest<GetMarkupGroupsByIdsTests.MarkupGroupsByIdsScenario>(fixture)
{
	[Fact]
	public async Task Batch_ReturnsOnlyRequestedGroupsWithoutDuplicates()
	{
		var manual = Scenario.Manual;
		var automatic = Scenario.Automatic;

		var result = await Mediator.Send(
			new GetMarkupGroupsByIdsQuery([manual.Id, automatic.Id, manual.Id, int.MaxValue]),
			CancellationToken);

		result.Groups.Keys.Should().BeEquivalentTo([manual.Id, automatic.Id]);
	}

	[Fact]
	public async Task SingleGroup_IsReturnedById()
	{
		var result = await Mediator.Send(new GetMarkupGroupsByIdsQuery(Scenario.Manual.Id), CancellationToken);

		result.Groups.Keys.Should().Equal(Scenario.Manual.Id);
	}

	[Fact]
	public async Task MissingGroup_ReturnsEmptyDictionary()
	{
		var result = await Mediator.Send(new GetMarkupGroupsByIdsQuery(int.MaxValue), CancellationToken);

		result.Groups.Should().BeEmpty();
	}

	[Fact]
	public async Task EmptyBatch_ReturnsEmptyDictionary()
	{
		var result = await Mediator.Send(
			new GetMarkupGroupsByIdsQuery(Array.Empty<int>()),
			CancellationToken);

		result.Groups.Should().BeEmpty();
	}

	public sealed class MarkupGroupsByIdsScenario : ReadScenario
	{
		public MarkupGroup Manual { get; private set; } = null!;

		public MarkupGroup Automatic { get; private set; } = null!;

		protected override IEnumerable<object> Seed()
		{
			Manual = new MarkupGroupDataBuilder(Faker).Build();
			Automatic = new MarkupGroupDataBuilder(Faker).AsAutoGenerated().Build();
			return [Manual, Automatic, new MarkupGroupDataBuilder(Faker).Build()];
		}
	}
}
