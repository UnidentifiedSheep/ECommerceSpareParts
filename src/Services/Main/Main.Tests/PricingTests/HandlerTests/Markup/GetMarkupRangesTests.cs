using Application.Common.Models;
using FluentAssertions;
using Pricing.Application.Queries.Markup.GetMarkupRanges;
using Pricing.Entities;
using Tests.Abstractions.Test;
using Tests.PricingTests.DataBuilders.Markup;

namespace Tests.PricingTests.HandlerTests.Markup;

public sealed class GetMarkupRangesTests(ReadScenarioFixture<GetMarkupRangesTests.MarkupRangesScenario> fixture)
	: ReadScenarioTest<GetMarkupRangesTests.MarkupRangesScenario>(fixture)
{
	[Fact]
	public async Task MissingGroup_ReturnsEmptyListWithoutRangesFromOtherGroups()
	{
		var result = await Mediator.Send(
			new GetMarkupRangesQuery(int.MaxValue, new Pagination(0, 10)),
			CancellationToken);

		result.Ranges.Should().BeEmpty();
	}

	[Theory]
	[InlineData(false)]
	[InlineData(true)]
	public async Task Pagination_ReturnsOnlySelectedGroupInBoundaryOrder(bool otherGroupFirst)
	{
		var selected = otherGroupFirst ? Scenario.SelectedAfterOther : Scenario.SelectedBeforeOther;

		var firstPage = await Mediator.Send(
			new GetMarkupRangesQuery(selected.Id, new Pagination(0, 2)),
			CancellationToken);
		var secondPage = await Mediator.Send(
			new GetMarkupRangesQuery(selected.Id, new Pagination(1, 2)),
			CancellationToken);

		firstPage.Ranges.Select(range => range.RangeStart).Should().Equal(0m, 10m);
		secondPage.Ranges.Should().ContainSingle().Which.RangeStart.Should().Be(20m);
		firstPage.Ranges
			.Concat(secondPage.Ranges)
			.Select(range => range.Id)
			.Should()
			.BeEquivalentTo(selected.MarkupRanges.Select(range => range.Id));
	}

	[Fact]
	public async Task PageBeyondLast_DoesNotReturnRangesOfAnotherGroup()
	{
		var result = await Mediator.Send(
			new GetMarkupRangesQuery(Scenario.SingleRange.Id, new Pagination(1, 1)),
			CancellationToken);

		result.Ranges.Should().BeEmpty();
	}

	public sealed class MarkupRangesScenario : ReadScenario
	{
		public MarkupGroup SelectedAfterOther { get; private set; } = null!;

		public MarkupGroup SelectedBeforeOther { get; private set; } = null!;

		public MarkupGroup SingleRange { get; private set; } = null!;

		protected override async Task PrepareAsync()
		{
			await AddInOrder(OtherBuilder().Build());
			SelectedAfterOther = await AddInOrder(SelectedBuilder().Build());
			SelectedBeforeOther = await AddInOrder(SelectedBuilder().Build());
			SingleRange = await AddInOrder(new MarkupGroupDataBuilder(Faker).Build());
			await AddInOrder(OtherBuilder().Build());
		}

		protected override IEnumerable<object> Seed() => [];

		private async Task<MarkupGroup> AddInOrder(MarkupGroup group)
		{
			Context.Add(group);
			await Context.SaveChangesAsync(CancellationToken);
			return group;
		}

		private MarkupGroupDataBuilder SelectedBuilder()
			=> new MarkupGroupDataBuilder(Faker)
				.WithRange(20m, 30m, 0.1m)
				.WithRange(0m, 10m, 0.2m)
				.WithRange(10m, 20m, 0.3m);

		private MarkupGroupDataBuilder OtherBuilder()
			=> new MarkupGroupDataBuilder(Faker).AsAutoGenerated()
				.WithRange(5m, 15m, 0.4m)
				.WithRange(15m, 25m, 0.5m);
	}
}

public class GetMarkupRangesValidationTests : ValidationTest<GetMarkupRangesValidation, GetMarkupRangesQuery>
{
	[Theory]
	[InlineData(0)]
	[InlineData(-1)]
	public async Task InvalidGroupId_IsRejected(int groupId)
	{
		var result = await ValidateAsync(new GetMarkupRangesQuery(groupId, new Pagination(0, 10)));
		result.ShouldHaveValidationErrorFor("GroupId");
	}

	[Theory]
	[InlineData(-1, 10)]
	[InlineData(0, 0)]
	[InlineData(0, 101)]
	public async Task InvalidPagination_IsRejected(int page, int size)
	{
		var result = await ValidateAsync(new GetMarkupRangesQuery(1, new Pagination(page, size)));
		result.ShouldHaveValidationErrorFor(page < 0 ? "Pagination.Page" : "Pagination.Size");
	}
}
