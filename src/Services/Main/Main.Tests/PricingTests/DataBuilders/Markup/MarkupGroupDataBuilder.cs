using Bogus;
using Pricing.Entities;
using Tests.Abstractions;

namespace Tests.PricingTests.DataBuilders.Markup;

public sealed class MarkupGroupDataBuilder(Faker faker) : BuilderBase<MarkupGroup>(faker)
{
	private readonly List<MarkupRange> _ranges = [];
	private string? _name;
	private Guid? _sourceMessageId;

	public MarkupGroupDataBuilder WithName(string name)
	{
		_name = name;
		return this;
	}

	public MarkupGroupDataBuilder AsAutoGenerated()
	{
		_sourceMessageId = Guid.NewGuid();
		return this;
	}

	public MarkupGroupDataBuilder WithRange(
		decimal start,
		decimal end,
		decimal markup)
	{
		_ranges.Add(
			MarkupRange.Create(
				start,
				end,
				markup));
		return this;
	}

	public override MarkupGroup Build()
		=> MarkupGroup.Create(
			_name ?? Faker.Commerce.ProductName(),
			1,
			_ranges.Count == 0
				?
				[
					MarkupRange.Create(
						0m,
						100m,
						0.2m)
				]
				: _ranges,
			_sourceMessageId);
}
