using Application.Common.Interfaces.Currency;
using Application.Common.Interfaces.Repositories;
using Application.Common.Interfaces.Settings;
using FluentAssertions;
using Internal.Integration.Core.Interfaces.Main;
using Microsoft.Extensions.DependencyInjection;
using Moq;
using Pricing.Application.Handlers.Markup;
using Pricing.Application.Interfaces.Cache;
using Pricing.Application.Services.Markup;
using Pricing.Entities;
using Pricing.Entities.Settings;
using Pricing.Integration.Tests.DataBuilders.Markup;
using Tests.Extensions;
using Tests.TestContainers.Combined;
using MarkupModel = Pricing.Application.Models.Markup;

namespace Pricing.Integration.Tests.Services.Markup;

public sealed class MarkupInitializerTests(CombinedContainerFixture fixture) : IntegrationTest(fixture)
{
	[Fact]
	public async Task NoAutomaticGroup_UsesDefaultMarkupEvenWhenManualGroupsExist()
	{
		await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		await SetPricingSettings();
		var container = new MarkupContainer();

		await Initializer(container).Initialize(CancellationToken);

		container.Initialized.Should().BeTrue();
		container.DefaultCurrencyId.Should().Be(1);
		container.DefaultMarkup.Value.Should().Be(0.35m);
		container.GetForDefaultOrNull(10m).Should().BeNull();
	}

	[Fact]
	public async Task DeletingLastAutomaticGroup_ClearsOldRangesAndUsesDefaultMarkup()
	{
		await SetPricingSettings();
		await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		var group = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context);
		var container = new MarkupContainer();
		container.Initialize(1, new MarkupModel(0.2m), [MarkupRange.Create(0m, 100m, 0.9m)],
			new Dictionary<int, IEnumerable<MarkupRange>> { [2] = [MarkupRange.Create(0m, 100m, 0.8m)] });
		var oldVersion = container.CurrentVersion;
		await Mediator.Send(new DeleteMarkupCommand(group.Id), CancellationToken);

		await Initializer(container).Initialize(CancellationToken);

		container.GetForDefaultOrNull(10m).Should().BeNull();
		container.GetForCurrencyOrNull(2, 10m).Should().BeNull();
		container.DefaultMarkup.Value.Should().Be(0.35m);
		container.CurrentVersion.Should().NotBe(oldVersion);
	}

	[Fact]
	public async Task ExplicitlySelectedMissingGroup_StillThrows()
	{
		await SetPricingSettings(int.MaxValue);

		await Assert.ThrowsAsync<InvalidOperationException>(() =>
			Initializer(new MarkupContainer()).Initialize(CancellationToken));
	}

	private MarkupInitializer Initializer(MarkupContainer container)
	{
		var currencies = new Mock<ICachedCurrencyProvider>();
		currencies.Setup(x => x.GetBaseCurrencyIdAsync(It.IsAny<CancellationToken>())).ReturnsAsync(1);
		return new MarkupInitializer(container,
			Scope.ServiceProvider.GetRequiredService<IReadRepository<MarkupGroup, int>>(),
			Scope.ServiceProvider.GetRequiredService<ISettingsService>(),
			Mock.Of<IMainClient>(), Mock.Of<ICurrencyConverter>(), Mock.Of<ICurrencyRatesProvider>(),
			currencies.Object);
	}

	private Task SetPricingSettings(int? selectedId = null) =>
		Scope.ServiceProvider.GetRequiredService<ISettingsService>().SetSetting(
			new PricingSetting(new PricingSettingData { SelectedMarkupId = selectedId, DefaultMarkup = 0.35m }),
			CancellationToken);
}
