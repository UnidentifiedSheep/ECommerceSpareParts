using Application.Common.Models;
using FluentAssertions;
using Pricing.Application.Handlers.Markup.GetMarkupRanges;
using Pricing.Integration.Tests.DataBuilders.Markup;
using Tests.Extensions;
using Tests.TestContainers.Combined;

namespace Pricing.Integration.Tests.HandlerTests.Markup;

public sealed class GetMarkupRangesTests(CombinedContainerFixture fixture) : IntegrationTest(fixture)
{
	[Fact]
	public async Task EmptyDatabase_ReturnsEmptyList()
	{
		var result = await Mediator.Send(new GetMarkupRangesQuery(new Pagination(0, 10)), CancellationToken);

		result.Ranges.Should().BeEmpty();
	}

	[Fact]
	public async Task Pagination_AppliesToRangesAcrossGroupsInBoundaryOrder()
	{
		var first = await new MarkupGroupDataBuilder(Faker)
			.WithRange(20m, 30m, 0.1m).WithRange(0m, 10m, 0.2m).BuildAndAddToDb(Context);
		var second = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated()
			.WithRange(10m, 20m, 0.3m).BuildAndAddToDb(Context);
		var expectedIds = first.MarkupRanges.Concat(second.MarkupRanges)
			.OrderBy(x => x.RangeStart).ThenBy(x => x.Id)
			.Select(x => x.Id).ToArray();

		var firstPage = await Mediator.Send(new GetMarkupRangesQuery(new Pagination(0, 2)), CancellationToken);
		var secondPage = await Mediator.Send(new GetMarkupRangesQuery(new Pagination(1, 2)), CancellationToken);

		firstPage.Ranges.Select(x => x.Id).Should().Equal(expectedIds.Take(2));
		secondPage.Ranges.Select(x => x.Id).Should().Equal(expectedIds.Skip(2));
	}

	[Theory]
	[InlineData(100)]
	[InlineData(10)]
	public async Task EqualStarts_UseIdForStablePagination(int secondEnd)
	{
		var first = await new MarkupGroupDataBuilder(Faker)
			.WithRange(0m, 100m, 0.1m).BuildAndAddToDb(Context);
		var second = await new MarkupGroupDataBuilder(Faker)
			.WithRange(0m, secondEnd, 0.2m).BuildAndAddToDb(Context);

		var firstPage = await Mediator.Send(new GetMarkupRangesQuery(new Pagination(0, 1)), CancellationToken);
		var secondPage = await Mediator.Send(new GetMarkupRangesQuery(new Pagination(1, 1)), CancellationToken);

		firstPage.Ranges.Select(x => x.Id).Should().Equal(first.MarkupRanges.Single().Id);
		secondPage.Ranges.Select(x => x.Id).Should().Equal(second.MarkupRanges.Single().Id);
	}

	[Fact]
	public async Task PageBeyondLast_ReturnsEmptyList()
	{
		await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);

		var result = await Mediator.Send(new GetMarkupRangesQuery(new Pagination(1, 10)), CancellationToken);

		result.Ranges.Should().BeEmpty();
	}

	[Theory]
	[InlineData(-1, 10)]
	[InlineData(0, 0)]
	[InlineData(0, 101)]
	public async Task InvalidPagination_IsRejected(int page, int size)
	{
		await Assert.ThrowsAsync<ValidationException>(() =>
			Mediator.Send(new GetMarkupRangesQuery(new Pagination(page, size)), CancellationToken));
	}
}
