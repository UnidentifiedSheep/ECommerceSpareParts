using Application.Common.Models;
using FluentAssertions;
using Pricing.Application.Handlers.Markup.GetMarkupRanges;
using Pricing.Integration.Tests.DataBuilders.Markup;
using Tests.Extensions;
using Tests.TestContainers.Combined;

namespace Pricing.Integration.Tests.HandlerTests.Markup;

public sealed class GetMarkupRangesTests(CombinedContainerFixture fixture) : IntegrationTest(fixture)
{
	[Fact]
	public async Task MissingGroup_ReturnsEmptyListWithoutRangesFromOtherGroups()
	{
		await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context, CancellationToken);

		var result = await Mediator.Send(new GetMarkupRangesQuery(int.MaxValue, new Pagination(0, 10)), CancellationToken);

		result.Ranges.Should().BeEmpty();
	}

	[Theory]
	[InlineData(false)]
	[InlineData(true)]
	public async Task Pagination_ReturnsOnlySelectedGroupInBoundaryOrder(bool otherGroupFirst)
	{
		var selectedBuilder = new MarkupGroupDataBuilder(Faker)
			.WithRange(20m, 30m, 0.1m).WithRange(0m, 10m, 0.2m).WithRange(10m, 20m, 0.3m);
		var otherBuilder = new MarkupGroupDataBuilder(Faker).AsAutoGenerated()
			.WithRange(5m, 15m, 0.4m).WithRange(15m, 25m, 0.5m);
		if (otherGroupFirst) await otherBuilder.BuildAndAddToDb(Context, CancellationToken);
		var selected = await selectedBuilder.BuildAndAddToDb(Context, CancellationToken);
		if (!otherGroupFirst) await otherBuilder.BuildAndAddToDb(Context, CancellationToken);

		var firstPage = await Mediator.Send(new GetMarkupRangesQuery(selected.Id, new Pagination(0, 2)), CancellationToken);
		var secondPage = await Mediator.Send(new GetMarkupRangesQuery(selected.Id, new Pagination(1, 2)), CancellationToken);

		firstPage.Ranges.Select(range => range.RangeStart).Should().Equal(0m, 10m);
		secondPage.Ranges.Should().ContainSingle().Which.RangeStart.Should().Be(20m);
		firstPage.Ranges.Concat(secondPage.Ranges).Select(range => range.Id)
			.Should().BeEquivalentTo(selected.MarkupRanges.Select(range => range.Id));
	}

	[Fact]
	public async Task PageBeyondLast_DoesNotReturnRangesOfAnotherGroup()
	{
		var selected = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context, CancellationToken);
		await new MarkupGroupDataBuilder(Faker).WithRange(0m, 10m, 0.1m).WithRange(10m, 20m, 0.2m)
			.BuildAndAddToDb(Context, CancellationToken);

		var result = await Mediator.Send(new GetMarkupRangesQuery(selected.Id, new Pagination(1, 1)), CancellationToken);

		result.Ranges.Should().BeEmpty();
	}

	[Theory]
	[InlineData(0)]
	[InlineData(-1)]
	public async Task InvalidGroupId_IsRejected(int groupId)
	{
		await Assert.ThrowsAsync<ValidationException>(() =>
			Mediator.Send(new GetMarkupRangesQuery(groupId, new Pagination(0, 10)), CancellationToken));
	}

	[Theory]
	[InlineData(-1, 10)]
	[InlineData(0, 0)]
	[InlineData(0, 101)]
	public async Task InvalidPagination_IsRejected(int page, int size)
	{
		await Assert.ThrowsAsync<ValidationException>(() =>
			Mediator.Send(new GetMarkupRangesQuery(1, new Pagination(page, size)), CancellationToken));
	}
}
