using Application.Common.Models;
using FluentAssertions;
using Pricing.Application.Handlers.Markup.GetMarkups;
using Pricing.Integration.Tests.DataBuilders.Markup;
using Tests.Extensions;
using Tests.TestContainers.Combined;

namespace Pricing.Integration.Tests.HandlerTests.Markup;

public sealed class GetMarkupsTests(CombinedContainerFixture fixture) : IntegrationTest(fixture)
{
	[Fact]
	public async Task EmptyDatabase_ReturnsEmptyList()
	{
		var result = await Mediator.Send(new GetMarkupsQuery(new Pagination(0, 10)), CancellationToken);

		result.Groups.Should().BeEmpty();
	}

	[Fact]
	public async Task Pagination_ReturnsManualAndAutomaticGroupsInStableOrder()
	{
		var first = await new MarkupGroupDataBuilder(Faker)
			.WithRange(0m, 10m, 0.2m).WithRange(10m, 100m, 0.1m).BuildAndAddToDb(Context, CancellationToken);
		var second = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context, CancellationToken);
		var third = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context, CancellationToken);

		var firstPage = await Mediator.Send(new GetMarkupsQuery(new Pagination(0, 2)), CancellationToken);
		var secondPage = await Mediator.Send(new GetMarkupsQuery(new Pagination(1, 2)), CancellationToken);

		firstPage.Groups.Select(x => x.Id).Should().Equal(first.Id, second.Id);
		secondPage.Groups.Select(x => x.Id).Should().Equal(third.Id);
	}

	[Fact]
	public async Task PageBeyondLast_ReturnsEmptyList()
	{
		await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context, CancellationToken);

		var result = await Mediator.Send(new GetMarkupsQuery(new Pagination(2, 10)), CancellationToken);

		result.Groups.Should().BeEmpty();
	}

	[Fact]
	public async Task SearchByName_TrimsTermAndIgnoresCase()
	{
		var retail = await new MarkupGroupDataBuilder(Faker).WithName("Retail markup").BuildAndAddToDb(Context, CancellationToken);
		await new MarkupGroupDataBuilder(Faker).WithName("Wholesale markup").BuildAndAddToDb(Context, CancellationToken);

		var result = await Mediator.Send(new GetMarkupsQuery(new Pagination(0, 10), "  RETAIL  "), CancellationToken);

		result.Groups.Select(group => group.Id).Should().Equal(retail.Id);
	}

	[Fact]
	public async Task Search_FiltersBeforePagination()
	{
		var first = await new MarkupGroupDataBuilder(Faker).WithName("Retail first").BuildAndAddToDb(Context, CancellationToken);
		await new MarkupGroupDataBuilder(Faker).WithName("Wholesale").BuildAndAddToDb(Context, CancellationToken);
		var second = await new MarkupGroupDataBuilder(Faker).WithName("Retail second").BuildAndAddToDb(Context, CancellationToken);

		var firstPage = await Mediator.Send(new GetMarkupsQuery(new Pagination(0, 1), "Retail"), CancellationToken);
		var secondPage = await Mediator.Send(new GetMarkupsQuery(new Pagination(1, 1), "Retail"), CancellationToken);
		var lastPage = await Mediator.Send(new GetMarkupsQuery(new Pagination(2, 1), "Retail"), CancellationToken);

		firstPage.Groups.Select(group => group.Id).Should().Equal(first.Id);
		secondPage.Groups.Select(group => group.Id).Should().Equal(second.Id);
		lastPage.Groups.Should().BeEmpty();
	}

	[Theory]
	[InlineData("%")]
	[InlineData("_")]
	[InlineData("\\")]
	public async Task Search_TreatsPatternCharactersLiterally(string term)
	{
		var selected = await new MarkupGroupDataBuilder(Faker).WithName($"Special {term} markup").BuildAndAddToDb(Context, CancellationToken);
		await new MarkupGroupDataBuilder(Faker).WithName("Special other markup").BuildAndAddToDb(Context, CancellationToken);

		var result = await Mediator.Send(new GetMarkupsQuery(new Pagination(0, 10), term), CancellationToken);

		result.Groups.Select(group => group.Id).Should().Equal(selected.Id);
	}

	[Fact]
	public async Task BlankSearchTerm_DoesNotFilterGroups()
	{
		var group = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context, CancellationToken);

		var result = await Mediator.Send(new GetMarkupsQuery(new Pagination(0, 10), "   "), CancellationToken);

		result.Groups.Select(item => item.Id).Should().Equal(group.Id);
	}

	[Fact]
	public async Task TooLongSearchTerm_IsRejected()
	{
		await Assert.ThrowsAsync<ValidationException>(() =>
			Mediator.Send(new GetMarkupsQuery(new Pagination(0, 10), new string('a', 129)), CancellationToken));
	}
}
