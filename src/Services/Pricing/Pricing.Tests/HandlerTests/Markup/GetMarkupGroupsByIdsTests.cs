using FluentAssertions;
using Pricing.Application.Handlers.Markup;
using Pricing.Integration.Tests.DataBuilders.Markup;
using Tests.Extensions;
using Tests.TestContainers.Combined;

namespace Pricing.Integration.Tests.HandlerTests.Markup;

public sealed class GetMarkupGroupsByIdsTests(CombinedContainerFixture fixture) : IntegrationTest(fixture)
{
	[Fact]
	public async Task Batch_ReturnsOnlyRequestedGroupsWithoutDuplicates()
	{
		var manual = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		var automatic = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context);
		await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);

		var result = await Mediator.Send(
			new GetMarkupGroupsByIdsQuery([manual.Id, automatic.Id, manual.Id, int.MaxValue]), CancellationToken);

		result.Groups.Keys.Should().BeEquivalentTo([manual.Id, automatic.Id]);
	}

	[Fact]
	public async Task SingleGroup_IsReturnedById()
	{
		var group = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);

		var result = await Mediator.Send(new GetMarkupGroupsByIdsQuery(group.Id), CancellationToken);

		result.Groups.Keys.Should().Equal(group.Id);
	}

	[Fact]
	public async Task MissingGroup_ReturnsEmptyDictionary()
	{
		var result = await Mediator.Send(new GetMarkupGroupsByIdsQuery(int.MaxValue), CancellationToken);

		result.Groups.Should().BeEmpty();
	}

	[Fact]
	public async Task EmptyBatch_ReturnsEmptyDictionary()
	{
		var result = await Mediator.Send(new GetMarkupGroupsByIdsQuery(Array.Empty<int>()), CancellationToken);

		result.Groups.Should().BeEmpty();
	}
}
