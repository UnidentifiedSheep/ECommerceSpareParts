using Application.Common.Interfaces.Settings;
using FluentAssertions;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Pricing.Application.Handlers.Markup;
using Pricing.Entities;
using Pricing.Entities.Exceptions.Markup;
using Pricing.Entities.Settings;
using Pricing.Integration.Tests.DataBuilders.Markup;
using Tests.Extensions;
using Tests.TestContainers.Combined;

namespace Pricing.Integration.Tests.HandlerTests.Markup;

public sealed class DeleteMarkupTests(CombinedContainerFixture fixture) : IntegrationTest(fixture)
{
	[Fact]
	public async Task InactiveGroup_DeletesGroupAndItsRangesWithoutChangingOtherGroups()
	{
		var deleted = await new MarkupGroupDataBuilder(Faker)
			.WithRange(0m, 10m, 0.2m).WithRange(10m, 100m, 0.1m).BuildAndAddToDb(Context);
		var retained = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		await SelectGroup(retained.Id);
		var rangeIds = deleted.MarkupRanges.Select(x => x.Id).ToList();

		await Mediator.Send(new DeleteMarkupCommand(deleted.Id), CancellationToken);

		(await Context.Set<MarkupGroup>().AsNoTracking().AnyAsync(x => x.Id == deleted.Id, CancellationToken))
			.Should().BeFalse();
		(await Context.Set<MarkupRange>().AsNoTracking().AnyAsync(x => rangeIds.Contains(x.Id), CancellationToken))
			.Should().BeFalse();
		(await Context.Set<MarkupGroup>().AsNoTracking().AnyAsync(x => x.Id == retained.Id, CancellationToken))
			.Should().BeTrue();
	}

	[Fact]
	public async Task SelectedGroup_CannotBeDeleted()
	{
		var group = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		await SelectGroup(group.Id);

		await Assert.ThrowsAsync<CurrenMarkupGroupCanNotBeDeletedException>(() =>
			Mediator.Send(new DeleteMarkupCommand(group.Id), CancellationToken));

		(await Context.Set<MarkupGroup>().AsNoTracking().AnyAsync(x => x.Id == group.Id, CancellationToken))
			.Should().BeTrue();
	}

	[Fact]
	public async Task SelectedGroup_WithStaleCachedSettings_CannotBeDeleted()
	{
		var previous = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		var current = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		await SelectGroup(previous.Id);
		var updatedSettings = new PricingSetting(new PricingSettingData { SelectedMarkupId = current.Id });
		await Context.Set<PricingSetting>()
			.ExecuteUpdateAsync(update => update.SetProperty(x => x.Json, updatedSettings.Json), CancellationToken);

		await Assert.ThrowsAsync<CurrenMarkupGroupCanNotBeDeletedException>(() =>
			Mediator.Send(new DeleteMarkupCommand(current.Id), CancellationToken));

		(await Context.Set<MarkupGroup>().AsNoTracking().AnyAsync(x => x.Id == current.Id, CancellationToken))
			.Should().BeTrue();
	}

	[Fact]
	public async Task LatestAutomaticGroup_WithAutomaticSelection_CannotBeDeleted()
	{
		await SelectGroup(null);
		var group = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context);

		await Assert.ThrowsAsync<CurrenMarkupGroupCanNotBeDeletedException>(() =>
			Mediator.Send(new DeleteMarkupCommand(group.Id), CancellationToken));

		(await Context.Set<MarkupRange>().AsNoTracking().AnyAsync(x => x.GroupId == group.Id, CancellationToken))
			.Should().BeTrue();
	}

	[Fact]
	public async Task OlderAutomaticGroup_CanBeDeleted()
	{
		await SelectGroup(null);
		var older = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context);
		var latest = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context);

		await Mediator.Send(new DeleteMarkupCommand(older.Id), CancellationToken);

		var ids = await Context.Set<MarkupGroup>().AsNoTracking().Select(x => x.Id).ToListAsync(CancellationToken);
		ids.Should().Equal(latest.Id);
	}

	[Fact]
	public async Task AutomaticGroup_WithExplicitlySelectedOtherGroup_CanBeDeleted()
	{
		var selected = await new MarkupGroupDataBuilder(Faker).BuildAndAddToDb(Context);
		var automatic = await new MarkupGroupDataBuilder(Faker).AsAutoGenerated().BuildAndAddToDb(Context);
		await SelectGroup(selected.Id);

		await Mediator.Send(new DeleteMarkupCommand(automatic.Id), CancellationToken);

		(await Context.Set<MarkupGroup>().AsNoTracking().AnyAsync(x => x.Id == automatic.Id, CancellationToken))
			.Should().BeFalse();
	}

	[Fact]
	public async Task MissingGroup_ThrowsNotFound()
	{
		await Assert.ThrowsAsync<MarkupGroupNotFoundException>(() =>
			Mediator.Send(new DeleteMarkupCommand(int.MaxValue), CancellationToken));
	}

	[Theory]
	[InlineData(0)]
	[InlineData(-1)]
	public async Task InvalidId_ThrowsValidationException(int id)
	{
		var exception = await Assert.ThrowsAsync<ValidationException>(() =>
			Mediator.Send(new DeleteMarkupCommand(id), CancellationToken));

		exception.Errors.Should().ContainSingle(x => x.ErrorCode == "markup.group.id.must.be.positive");
	}

	private Task SelectGroup(int? id) => Scope.ServiceProvider.GetRequiredService<ISettingsService>()
		.SetSetting(new PricingSetting(new PricingSettingData { SelectedMarkupId = id }), CancellationToken);
}
